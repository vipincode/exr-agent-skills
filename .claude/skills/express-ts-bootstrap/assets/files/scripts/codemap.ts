/**
 * Code map generator — writes codemap/*.md: every exported symbol in src/ and
 * test/, with its file, a compact signature, and the first sentence of the
 * comment above it. AI (and people) read the map instead of opening files to
 * find out what exists and where.
 *
 * Shared, identical file in express-ts-bootstrap and nextjs-bootstrap — it
 * understands both layouts (src/modules/* for Express; src/features/*,
 * src/components/*, src/app/* for Next.js). Keep the two copies identical.
 *
 *   tsx scripts/codemap.ts           regenerate codemap/
 *   tsx scripts/codemap.ts --check   exit 1 if codemap/ is stale (CI)
 *
 * Output is deterministic (sorted, no timestamps) so --check is a plain diff.
 * Parses syntax only (no type-checking), so it runs in well under a second.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import ts from "typescript";

const ROOT = process.cwd();
const OUT_DIR = path.join(ROOT, "codemap");
const SCAN_DIRS = ["src", "test"];
const MAX_SIG = 110;
const MAX_DESC = 110;
const HEADER = "<!-- Generated by scripts/codemap.ts — do not edit. Regenerated on every commit. -->";

interface Entry {
  name: string;
  kind: string;
  sig: string;
  desc: string;
}

interface FileMap {
  rel: string; // posix path from the project root, e.g. src/lib/http.ts
  about: string; // file-level comment (detached, i.e. followed by a blank line)
  entries: Entry[];
}

// ---------------------------------------------------------------------------
// Collect files
// ---------------------------------------------------------------------------

const SOURCE = /\.tsx?$/;
const SKIP_FILE = /\.(test|spec|stories)\.tsx?$/;

function walk(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const full = path.join(dir, d.name);
    if (d.isDirectory()) return d.name === "__tests__" || d.name === "node_modules" ? [] : walk(full);
    return SOURCE.test(d.name) && !SKIP_FILE.test(d.name) ? [full] : [];
  });
}

const toPosix = (p: string) => p.split(path.sep).join("/");

// ---------------------------------------------------------------------------
// Extract exports from one file
// ---------------------------------------------------------------------------

const squash = (s: string) => s.replace(/\s+/g, " ").trim();
const clip = (s: string, max: number) => (s.length > max ? `${s.slice(0, max - 1)}…` : s);

function hasExport(node: ts.Node): boolean {
  return ts.canHaveModifiers(node) && !!ts.getModifiers(node)?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
}

function isDefault(node: ts.Node): boolean {
  return ts.canHaveModifiers(node) && !!ts.getModifiers(node)?.some((m) => m.kind === ts.SyntaxKind.DefaultKeyword);
}

function cleanComment(raw: string): string {
  const joined = squash(
    raw
      .replace(/^\/\*\*?|\*\/$/g, "")
      .split("\n")
      .map((l) => l.replace(/^\s*(\*|\/\/)\s?/, ""))
      .join(" "),
  ).replace(/@\w+.*$/, "");
  const sentence = joined.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? joined;
  return clip(sentence, MAX_DESC);
}

/**
 * Split the comments above a node into the block attached to it (no blank line
 * between comment and code) and a detached block (followed by a blank line) —
 * by convention the detached block describes the whole file.
 */
function comments(node: ts.Node, text: string): { attached: string; detached: string } {
  const ranges = ts.getLeadingCommentRanges(text, node.getFullStart()) ?? [];
  let split = 0; // index of the first range in the attached block
  ranges.forEach((r, i) => {
    const nextStart = ranges[i + 1]?.pos ?? node.getStart();
    if (/\n[ \t]*\r?\n/.test(text.slice(r.end, nextStart))) split = i + 1;
  });
  const join = (rs: ts.CommentRange[]) => rs.map((r) => text.slice(r.pos, r.end)).join("\n");
  return {
    attached: cleanComment(join(ranges.slice(split))),
    detached: cleanComment(join(ranges.slice(0, split))),
  };
}

const leadingComment = (node: ts.Node, text: string) => comments(node, text).attached;

function params(fn: ts.SignatureDeclarationBase, sf: ts.SourceFile): string {
  const generics = fn.typeParameters ? `<${fn.typeParameters.map((t) => squash(t.getText(sf))).join(", ")}>` : "";
  const p = fn.parameters.map((x) => squash(x.getText(sf))).join(", ");
  const ret = fn.type ? `: ${squash(fn.type.getText(sf))}` : "";
  return `${generics}(${p})${ret}`;
}

function unwrap(expr: ts.Expression): ts.Expression {
  let e = expr;
  while (ts.isSatisfiesExpression(e) || ts.isAsExpression(e) || ts.isParenthesizedExpression(e)) e = e.expression;
  return e;
}

/** A short, human-meaningful description of a const's value. */
function describeValue(init: ts.Expression | undefined, sf: ts.SourceFile): { kind: string; sig: string } {
  if (!init) return { kind: "const", sig: "" };
  const e = unwrap(init);
  if (ts.isArrowFunction(e) || ts.isFunctionExpression(e)) return { kind: "fn", sig: params(e, sf) };
  if (ts.isObjectLiteralExpression(e)) {
    const keys = e.properties.map((p) => (p.name ? p.name.getText(sf) : "…"));
    return { kind: "const", sig: ` = { ${keys.join(", ")} }` };
  }
  if (ts.isCallExpression(e)) {
    // Show the outermost call chain head, e.g. z.object(…), paginationQuerySchema.extend(…).
    return { kind: "const", sig: ` = ${squash(e.expression.getText(sf))}(…)` };
  }
  if (ts.isNewExpression(e)) return { kind: "const", sig: ` = new ${e.expression.getText(sf)}(…)` };
  return { kind: "const", sig: ` = ${clip(squash(e.getText(sf)), 40)}` };
}

function extract(file: string): { about: string; entries: Entry[] } {
  const text = readFileSync(file, "utf8");
  const scriptKind = file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, scriptKind);
  const entries: Entry[] = [];
  const about = sf.statements.map((st) => comments(st, text).detached).find(Boolean) ?? "";
  const add = (name: string, kind: string, sig: string, node: ts.Node) =>
    entries.push({ name, kind, sig: clip(sig, MAX_SIG), desc: leadingComment(node, text) });

  // Ambient declaration files: list the interfaces they declare/augment.
  if (file.endsWith(".d.ts")) {
    const visit = (n: ts.Node, scope: string[]) => {
      if (ts.isModuleDeclaration(n)) {
        const name = n.name.getText(sf);
        const next = name === "global" ? scope : [...scope, name];
        if (n.body) ts.forEachChild(n.body, (c) => visit(c, next));
        return;
      }
      if (ts.isInterfaceDeclaration(n)) {
        const members = n.members.map((m) => m.name?.getText(sf) ?? "…");
        add([...scope, n.name.text].join("."), "augments", ` { ${members.join(", ")} }`, n);
      }
      ts.forEachChild(n, (c) => visit(c, scope));
    };
    visit(sf, []);
    return { about, entries };
  }

  for (const st of sf.statements) {
    if (ts.isExportDeclaration(st)) {
      // Re-exports (a module's index.ts): `export { a, default as b } from "./x.js"`.
      const from = st.moduleSpecifier ? ` ← ${(st.moduleSpecifier as ts.StringLiteral).text}` : "";
      const typeOnly = st.isTypeOnly ? "type" : "re-export";
      if (st.exportClause && ts.isNamedExports(st.exportClause)) {
        for (const el of st.exportClause.elements) {
          add(el.name.text, el.isTypeOnly || st.isTypeOnly ? "type" : typeOnly, from, st);
        }
      } else if (st.exportClause && ts.isNamespaceExport(st.exportClause)) {
        add(st.exportClause.name.text, "namespace", from, st);
      } else {
        add("*", "re-export", from, st);
      }
      continue;
    }
    if (ts.isExportAssignment(st)) {
      add("default", "default", ` = ${clip(squash(st.expression.getText(sf)), 40)}`, st);
      continue;
    }
    if (!hasExport(st)) continue;

    if (ts.isFunctionDeclaration(st)) {
      add(st.name?.text ?? "default", isDefault(st) ? "default fn" : "fn", params(st, sf), st);
    } else if (ts.isVariableStatement(st)) {
      for (const d of st.declarationList.declarations) {
        const { kind, sig } = describeValue(d.initializer, sf);
        add(d.name.getText(sf), kind, sig, st);
      }
    } else if (ts.isClassDeclaration(st)) {
      const methods = st.members
        .filter((m): m is ts.MethodDeclaration | ts.PropertyDeclaration =>
          ts.isMethodDeclaration(m) || ts.isPropertyDeclaration(m),
        )
        .filter((m) => !ts.getModifiers(m)?.some((x) => x.kind === ts.SyntaxKind.PrivateKeyword))
        .map((m) => m.name.getText(sf))
        .filter((n) => !n.startsWith("#"));
      add(st.name?.text ?? "default", "class", methods.length ? ` { ${methods.join(", ")} }` : "", st);
    } else if (ts.isInterfaceDeclaration(st)) {
      const members = st.members.map((m) => m.name?.getText(sf) ?? "…");
      add(st.name.text, "type", ` { ${members.join(", ")} }`, st);
    } else if (ts.isTypeAliasDeclaration(st)) {
      add(st.name.text, "type", ` = ${squash(st.type.getText(sf))}`, st);
    } else if (ts.isEnumDeclaration(st)) {
      add(st.name.text, "enum", ` { ${st.members.map((m) => m.name.getText(sf)).join(", ")} }`, st);
    }
  }
  return { about, entries };
}

// ---------------------------------------------------------------------------
// Group into shards
// ---------------------------------------------------------------------------

/**
 * Shard name for a file. Express: app, config, lib, middleware, modules/<name>.
 * Next.js: app (routes + proxy.ts), components-ui, components-shared,
 * features/<name>, hooks, lib, services. Both: types-constants, test-helpers.
 */
function shardOf(rel: string): string {
  const parts = rel.split("/");
  if (parts[0] === "test") return "test-helpers";
  if (parts[0] !== "src") return parts[0]!;
  const area = parts[1] ?? "";
  if (SOURCE.test(area)) return "app"; // src/app.ts, src/routes.ts, src/proxy.ts, …
  if ((area === "modules" || area === "features") && parts.length > 3) return `${area}/${parts[2]}`;
  if (area === "components") {
    const group = parts[2] ?? "";
    return group === "ui" || group === "shared" ? `components-${group}` : "components";
  }
  if (area === "types" || area === "constants") return "types-constants";
  return area;
}

function renderEntry(e: Entry): string {
  const desc = e.desc ? ` — ${e.desc}` : "";
  return `- \`${e.name}${e.sig}\` *${e.kind}*${desc}`;
}

function renderShard(name: string, files: FileMap[]): string {
  const lines = [HEADER, "", `# ${name}`, ""];
  if (name === "components-ui") {
    // CLI-managed primitives (shadcn): one compact line per file — the names are what matter.
    lines.push("CLI-managed primitives — compose them, never fork. Exports per file:", "");
    for (const f of files) {
      const names = f.entries.map((e) => e.name).join(", ") || "*(no exports)*";
      lines.push(`- \`${path.posix.basename(f.rel)}\`: ${names}`);
    }
    lines.push("");
    return lines.join("\n");
  }
  for (const f of files) {
    lines.push(`## ${f.rel}`);
    if (f.about) lines.push(`> ${f.about}`, "");
    lines.push(...(f.entries.length ? f.entries.map(renderEntry) : ["- *(no exports)*"]));
    lines.push("");
  }
  return lines.join("\n");
}

/** Mount paths from src/routes.ts: `apiRouter.use("/products", productRoutes)`. */
function mounts(): Map<string, string> {
  const file = path.join(ROOT, "src", "routes.ts");
  const found = new Map<string, string>();
  if (!existsSync(file)) return found;
  for (const m of readFileSync(file, "utf8").matchAll(/\.use\(\s*["'`]([^"'`]+)["'`]\s*,\s*(\w+)/g)) {
    found.set(m[2]!, m[1]!);
  }
  return found;
}

function renderIndex(shards: Map<string, FileMap[]>): string {
  const count = (fs: FileMap[]) => fs.reduce((n, f) => n + f.entries.length, 0);
  const mountOf = mounts();
  const lines = [
    HEADER,
    "",
    "# Code map",
    "",
    "Every exported symbol, by area. **Read this index first, then only the shard you need, then only",
    "the files you will change.** Grep is for confirming, not discovering. Modules are listed by their",
    "public surface (`index.ts`) — the only part other modules may import.",
    "",
    "| Shard | Files | Exports |",
    "| --- | --- | --- |",
  ];
  for (const [name, files] of shards) {
    lines.push(`| [${name}](${name}.md) | ${files.length} | ${count(files)} |`);
  }
  const modules = [...shards.keys()].filter((k) => k.startsWith("modules/") || k.startsWith("features/"));
  if (modules.length) {
    lines.push("", "## Public surfaces (`index.ts` — the only legal import from outside)", "");
    for (const m of modules) {
      const name = m.slice(m.indexOf("/") + 1);
      const index = shards.get(m)!.find((f) => /^src\/[^/]+\/[^/]+\/index\.tsx?$/.test(f.rel));
      const surface = index?.entries ?? [];
      const routes = surface.find((e) => e.name.endsWith("Routes"));
      const mount = routes && mountOf.get(routes.name);
      const names = surface.map((e) => (e.kind === "type" ? `type ${e.name}` : e.name));
      lines.push(`- **${name}**${mount ? ` (\`/api/v1${mount}\`)` : ""}: ${names.join(", ") || "*(no index.ts)*"}`);
    }
  }
  const routes = nextRoutes(shards.get("app") ?? []);
  if (routes.length) lines.push("", "## Routes (Next.js `src/app`)", "", ...routes);
  lines.push("");
  return lines.join("\n");
}

/** URL → file for Next.js App Router pages and route handlers. */
function nextRoutes(files: FileMap[]): string[] {
  return files
    .filter((f) => /^src\/app\/(.+\/)?(page|route)\.tsx?$/.test(f.rel))
    .map((f) => {
      const segments = f.rel
        .split("/")
        .slice(2, -1) // drop "src/app" and the file name
        .filter((s) => !/^\(.*\)$/.test(s) && !s.startsWith("@")); // route (groups) and @slots aren't URL segments
      const kind = /\/route\.tsx?$/.test(f.rel) ? "handler" : "page";
      return `- \`/${segments.join("/")}\` *${kind}* → ${f.rel}`;
    })
    .sort();
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function build(): Map<string, string> {
  const files = SCAN_DIRS.flatMap((d) => walk(path.join(ROOT, d)))
    .map((f) => ({ rel: toPosix(path.relative(ROOT, f)), ...extract(f) }))
    .sort((a, b) => a.rel.localeCompare(b.rel));

  const shards = new Map<string, FileMap[]>();
  for (const f of files) {
    const key = shardOf(f.rel);
    shards.set(key, [...(shards.get(key) ?? []), f]);
  }
  const sorted = new Map([...shards].sort(([a], [b]) => a.localeCompare(b)));

  const out = new Map<string, string>([["INDEX.md", renderIndex(sorted)]]);
  for (const [name, fs] of sorted) out.set(`${name}.md`, renderShard(name, fs));
  return out;
}

function existing(): Map<string, string> {
  const found = new Map<string, string>();
  const read = (dir: string) => {
    if (!existsSync(dir)) return;
    for (const d of readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, d.name);
      if (d.isDirectory()) read(full);
      else if (d.name.endsWith(".md")) {
        found.set(toPosix(path.relative(OUT_DIR, full)), readFileSync(full, "utf8").replace(/\r\n/g, "\n"));
      }
    }
  };
  read(OUT_DIR);
  return found;
}

const next = build();

if (process.argv.includes("--check")) {
  const current = existing();
  const stale = [
    ...[...next].filter(([k, v]) => current.get(k) !== v).map(([k]) => k),
    ...[...current.keys()].filter((k) => !next.has(k)),
  ];
  if (stale.length) {
    console.error(`codemap is stale (${stale.join(", ")}). Run: tsx scripts/codemap.ts`);
    process.exit(1);
  }
  console.log("codemap is up to date");
} else {
  rmSync(OUT_DIR, { recursive: true, force: true });
  for (const [rel, content] of next) {
    const target = path.join(OUT_DIR, rel);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  console.log(`codemap: ${next.size} files written to codemap/`);
}
